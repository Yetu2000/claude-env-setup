class GenerateScriptsTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.temp, ignore_errors=True)

    def generate_all(self, platform):
        ctx = fake_ctx(platform)
        plan_dir = os.path.join(self.temp, platform, "plan")
        backup = os.path.join(self.temp, platform, "backup it's")
        os.makedirs(plan_dir)
        os.makedirs(backup)
        state = MAC_STATE if platform == "darwin" else WIN_STATE
        plan = dict(PLAN_B, platform=platform)
        plan["jump_default"] = "HK-02 香港"
        return [
            gen.gen_switch(ctx, plan, plan_dir, backup),
            gen.gen_restore(ctx, backup, state["network"], "20260101-000000"),
            gen.gen_harden(ctx, plan_dir, state),
            gen.gen_killswitch(ctx, plan_dir),
            gen.gen_drills(ctx, plan, plan_dir),
        ]

    def test_mac_scripts(self):
        paths = self.generate_all("darwin")
        for path in paths:
            text = util.read_text(path)
            self.assertIsNone(gen.PLACEHOLDER.search(text), path)
            self.assertNotIn("\r\n", text)
        restore = util.read_text(paths[1])
        self.assertIn("-setwebproxy 'USB 10/100/1000 LAN' '10.0.0.8' '3128'", restore)
        self.assertNotIn("-setwebproxy 'Wi-Fi' '127.0.0.1'", restore, "本机代理不还原：由客户端自己重新设置")
        self.assertIn("-setdnsservers 'Wi-Fi' empty", restore)
        harden = util.read_text(paths[2])
        self.assertIn("-setv6off 'Wi-Fi'", harden)
        self.assertNotIn("-setv6off 'USB 10/100/1000 LAN'", harden, "手动 IPv6 不改")
        self.assertNotIn("Thunderbolt Bridge' 223", harden, "停用的服务不改")
        switch = util.read_text(paths[0])
        self.assertIn("RES_JSON='\"住宅出口\"'", switch)
        self.assertIn("backup it'\\''s", switch)
        ks = util.read_text(paths[3])
        for marker in ("CNET_GUARD_APPLY_EOF", "CNET_GUARD_WATCH_EOF", "CNET_GUARD_OFF_EOF", "CNET_GUARD_PLIST_EOF"):
            self.assertEqual(len(re.findall("^" + marker + "$", ks, re.M)), 1, marker)
        self.assertIn("com.apple/clash-guard", ks)
        self.assertIn("local.clash-guard", ks)
        dash = find_dash()
        if dash:
            for path in paths + [os.path.join(gen.TEMPLATE_DIR, "mac", n) for n in ("guard_apply.sh", "guard_watch.sh", "guard_off.sh")]:
                out = subprocess.run([dash, "-n", path], capture_output=True, text=True)
                self.assertEqual(out.returncode, 0, path + "\n" + out.stderr)

    def test_win_scripts(self):
        paths = self.generate_all("windows")
        for path in paths:
            with open(path, "rb") as handle:
                self.assertTrue(handle.read(3) == b"\xef\xbb\xbf", "PowerShell 5.1 需要 UTF-8 BOM：" + path)
            self.assertIsNone(gen.PLACEHOLDER.search(util.read_text(path)), path)
        restore = util.read_text(paths[1])
        self.assertIn("Enable-NetAdapterBinding -Name 'WLAN'", restore)
        self.assertNotIn("-Name 'Meta' -ComponentID", restore, "只还原物理网卡")
        self.assertNotIn("127.0.0.1:7897", restore, "本机代理不还原")
        self.assertTrue(os.path.exists(os.path.join(os.path.dirname(paths[1]), "restore.cmd")))
        if util.IS_WINDOWS:
            import cnet  # noqa: PLC0415

            self.assertEqual(cnet.precheck_paths(paths), [])

