    def test_ps_quote_curly(self):
        """PowerShell 把 ‘ ’ ‚ ‛ 也当单引号：订阅里的节点名不能借此截断字符串注入命令。"""
        name = "US \u2019curly\u2018 \u201a\u201b 'x' $(calc) \"dq\""
        quoted = util.ps_quote(name)
        if not util.IS_WINDOWS:
            return
        script = os.path.join(self.temp, "q.ps1")
        util.write_text(script, "[Console]::OutputEncoding=[Text.Encoding]::UTF8\n$v = " + quoted + "\n[Console]::Out.Write($v)\n", bom=True)
        out = subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script],
                             capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=60)
        self.assertEqual(out.stdout, name, out.stderr)

    @unittest.skipUnless(util.IS_WINDOWS, "需要 Windows PowerShell")
    def test_ps_functions_return_clean_booleans(self):
        """Write-Log 不能混进返回值：否则 if (-not (Wait-Claude)) 永远不触发，安全阀全部失效。"""
        body = gen.common(fake_ctx("windows")) + (
            "\nfunction Test-Claude { return $false }\n"
            "function Get-CorePipe { return $null }\n"
            "$results = @()\n"
            "$r = Wait-Claude 1; $results += ('wait:' + ($r -is [bool]) + ':' + $r)\n"
            "$r = Select-Node 'g' '\"n\"'; $results += ('select:' + ($r -is [bool]) + ':' + $r)\n"
            "$r = Test-NodeDelay 'n'; $results += ('delay:' + ($r -is [bool]) + ':' + $r)\n"
            "$r = Wait-Ready 1; $results += ('ready:' + ($r -is [bool]) + ':' + $r)\n"
            "[Console]::Out.WriteLine('RESULT ' + ($results -join ' '))\n"
        )
        script = os.path.join(self.temp, "bool.ps1")
        util.write_text(script, body, newline="\r\n", bom=True)
        out = subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script],
                             capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=90)
        line = [entry for entry in out.stdout.splitlines() if entry.startswith("RESULT ")]
        self.assertTrue(line, out.stdout + out.stderr)
        self.assertEqual(line[0], "RESULT wait:True:False select:True:False delay:True:False ready:True:False")

