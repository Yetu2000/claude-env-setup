class RenderTest(unittest.TestCase):
    def test_rule_order(self):
        rules = render.build_rules(PLAN_A)
        index = {r: i for i, r in enumerate(rules)}
        self.assertTrue(rules[0].startswith("DOMAIN-SUFFIX,claude.ai,海外出口"))
        self.assertEqual(rules[-2:], ["MATCH,海外出口", "MATCH,REJECT"])
        # 每条走海外出口的规则后面紧跟同条件的 REJECT：出口不支持 UDP 时，UDP 不会落到 DIRECT
        for i, rule in enumerate(rules):
            if rule.endswith(",海外出口"):
                self.assertEqual(rules[i + 1], rule[: -len("海外出口")] + "REJECT", rule)
        self.assertLess(index["DOMAIN-KEYWORD,mirrorakam,DIRECT"], index["GEOSITE,geolocation-!cn,海外出口"])
        self.assertLess(index["GEOSITE,geolocation-!cn,海外出口"], index["RULE-SET,direct-domain,DIRECT"])
        self.assertIn("RULE-SET,china-ip,DIRECT,no-resolve", rules)
        self.assertIn("IP-CIDR,100.64.0.0/10,DIRECT,no-resolve", rules)
        for rule in rules:
            if rule.startswith(("IP-CIDR", "RULE-SET,china-ip")):
                self.assertTrue(rule.endswith("no-resolve"), "IP 规则必须 no-resolve：" + rule)
        directs = [r for r in rules if ",DIRECT" in r]
        for rule in directs:
            kind, payload = rule.split(",")[0:2]
            self.assertTrue(kind in ("IP-CIDR", "IP-CIDR6", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "PROCESS-NAME", "RULE-SET"), rule)

    def test_b_mode(self):
        data = render.build_data(PLAN_B)
        res = data["extraProxies"][0]
        self.assertEqual(res["dialer-proxy"], "跳板")
        self.assertFalse(res["udp"])
        self.assertIn("IP-CIDR,203.0.113.9/32,跳板,no-resolve", data["rules"])
        groups = {g["name"]: g for g in data["groups"]}
        self.assertEqual([m["name"] for m in groups["海外出口"]["members"]], ["住宅出口", util.DRILL_NODE])
        self.assertIn("HK-02 香港", [m["name"] for m in groups["跳板"]["members"]])
        self.assertEqual(groups["跳板"]["members"][-1]["name"], util.DRILL_NODE, "跳板组末尾有演练节点：全部失效时断网而不是空组")
        self.assertEqual(data["ruleProviders"]["direct-domain"]["proxy"], "跳板")

    def test_domain_residential(self):
        plan = json.loads(json.dumps(PLAN_B))
        plan["residential"]["server"] = "res.example.net"
        self.assertIn("DOMAIN,res.example.net,跳板", render.build_rules(plan))

    def test_validation(self):
        bad = json.loads(json.dumps(PLAN_A))
        bad["exit"]["region"] = "HK"
        with self.assertRaises(render.PlanError):
            render.build_data(bad)
        bad = json.loads(json.dumps(PLAN_B))
        bad["residential"]["port"] = 70000
        with self.assertRaises(render.PlanError):
            render.build_data(bad)
        bad = json.loads(json.dumps(PLAN_B))
        bad["residential"]["password"] = ""
        with self.assertRaises(render.PlanError):
            render.build_data(bad)

    def test_dns_design(self):
        dns = render.build_dns()
        self.assertEqual(dns["enhanced-mode"], "fake-ip")
        self.assertFalse(dns["ipv6"])
        self.assertTrue(dns["respect-rules"])
        self.assertEqual(dns["proxy-server-nameserver"], ["223.5.5.5", "119.29.29.29"])
        self.assertEqual(dns["direct-nameserver"], ["223.5.5.5", "119.29.29.29"])
        self.assertTrue(all(ns.startswith("https://") for ns in dns["nameserver"]))
        self.assertEqual(dns["nameserver-policy"]["rule-set:direct-domain"], ["223.5.5.5", "119.29.29.29"])

    def test_script_has_no_placeholder_credentials(self):
        script = render.render_script(PLAN_B)
        self.assertIn(render.BEGIN, script)
        self.assertIn('"password": "p\\"$`x"', script)
        masked = render.render_script(PLAN_B, with_credentials=False)
        self.assertNotIn("p\\\"$`x", masked)


@unittest.skipUnless(shutil.which("node"), "需要 node")
class ScriptExecutionTest(unittest.TestCase):
    def run_script(self, plan, config):
        temp = tempfile.mkdtemp()
        try:
            script = os.path.join(temp, "Script.js")
            util.write_text(script, render.render_script(plan))
            cfg = os.path.join(temp, "sub.json")
            util.write_json(cfg, config)
            out = subprocess.run(["node", os.path.join(HERE, "run_script.js"), script, cfg], capture_output=True, text=True, encoding="utf-8")
            self.assertEqual(out.returncode, 0, out.stderr)
            return json.loads(out.stdout)
        finally:
            shutil.rmtree(temp, ignore_errors=True)

    def test_matches_simulation(self):
        sub = {"proxies": SUB, "proxy-groups": [{"name": "P", "type": "select", "proxies": ["JP-01 东京", "DIRECT"]}],
               "rules": ["MATCH,P"], "rule-providers": {"x": {"type": "http", "behavior": "domain", "url": "https://e.com", "path": "./x"}}}
        for plan in (PLAN_A, PLAN_B):
            result = self.run_script(plan, sub)
            simulated = render.simulate(plan, SUB, with_credentials=True)
            ours = [g for g in result["proxy-groups"] if g["name"] in ("海外出口", "跳板")]
            self.assertEqual(ours, simulated["proxy-groups"])
            self.assertEqual(result["rules"], simulated["rules"])
            self.assertEqual(list(result["rule-providers"]), ["direct-domain", "china-ip"])
            self.assertFalse(result["ipv6"])
            for group in ours:
                self.assertNotIn("DIRECT", group["proxies"])
            self.assertIn("P", [g["name"] for g in result["proxy-groups"]], "订阅自己的组保留")

    def test_missing_exit_fails_closed(self):
        result = self.run_script(PLAN_A, {"proxies": [SUB[1]]})
        group = [g for g in result["proxy-groups"] if g["name"] == "海外出口"][0]
        self.assertEqual(group["proxies"], [util.DRILL_NODE], "出口节点不在了：只剩演练节点 = 断网，不回落直连")

    def test_provider_nodes_use_filter(self):
        plan = {"mode": "A", "platform": "windows", "exit": {"name": "JP (1)", "provider": "airport"}}
        result = self.run_script(plan, {"proxies": [], "proxy-providers": {"airport": {"type": "http", "url": "https://e.com"}}})
        group = [g for g in result["proxy-groups"] if g["name"] == "海外出口"][0]
        self.assertEqual(group["use"], ["airport"])
        self.assertEqual(group["filter"], "^(JP \\(1\\))$")

    def test_empty_config(self):
        result = self.run_script(PLAN_A, {})
        self.assertEqual(result["rules"][-1], "MATCH,REJECT")


