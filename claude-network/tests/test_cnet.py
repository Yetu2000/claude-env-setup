class YamlMiniTest(unittest.TestCase):
    def test_top_scalar(self):
        text = yamlmini.set_top_scalar(CONFIG_YAML, "ipv6", False)
        self.assertIn("\nipv6: false\n", text)
        self.assertEqual(yamlmini.get_top_scalar(text, "mixed-port"), 7897)
        self.assertIn("secret: abc", text)
        added = yamlmini.set_top_scalar(CONFIG_YAML, "find-process-mode", "strict")
        self.assertIn("find-process-mode: strict", added)

    def test_child_and_list(self):
        text = yamlmini.set_child(CONFIG_YAML, "tun", "stack", "gvisor")
        text = yamlmini.set_child(text, "tun", "dns-hijack", ["any:53", "tcp://any:53"])
        text = yamlmini.set_child(text, "tun", "auto-detect-interface", True)
        self.assertEqual(yamlmini.get_child_scalar(text, "tun", "stack"), "gvisor")
        self.assertEqual(yamlmini.get_child_list(text, "tun", "dns-hijack"), ["any:53", "tcp://any:53"])
        self.assertEqual(text.count("dns-hijack"), 1)
        self.assertIn("secret: abc", text)
        # tun 之后的键不被吞掉
        self.assertEqual(yamlmini.get_top_scalar(text, "unified-delay"), True)

    def test_missing_parent_appended(self):
        text = yamlmini.set_child("mixed-port: 1\n", "tun", "stack", "gvisor")
        self.assertIn("tun:\n  stack: gvisor", text)

    def test_flow_style_rejected(self):
        with self.assertRaises(yamlmini.YamlEditError):
            yamlmini.set_child("tun: {enable: true}\n", "tun", "stack", "gvisor")

    def test_profile_dns_all_off(self):
        text = yamlmini.map_block_set_all(VERGE_YAML, "profile_dns_settings", "enabled", False)
        self.assertNotIn("enabled: true", text)
        self.assertIn("pac_file_content: |", text)

    def test_parse_profiles(self):
        parsed = yamlmini.parse_verge_profiles(PROFILES_YAML)
        self.assertEqual(parsed["current"], "RsdSplit9k2X")
        item = [i for i in parsed["items"] if i["uid"] == "RsdSplit9k2X"][0]
        self.assertEqual(item["name"], "我的订阅")
        self.assertEqual(item["option"]["script"], "sIbr")

    def test_comment_only_extension_is_empty(self):
        self.assertTrue(yamlmini.is_effectively_empty_yaml("# Profile Enhancement Merge Template\n\n"))
        self.assertFalse(yamlmini.is_effectively_empty_yaml("profile:\n  store-selected: true\n"))


